"""Live Spanish, French, Japanese and Chinese phrasings, the pair to stress_phrases_en.py.

The same rules: expect only for fields where the person spoke unambiguously;
expect=None is for reading by hand. Whatever the language, the facts come out
in the same canonical forms as for English: brands and models in Latin letters
as the maker writes them, colours, levels and weekdays in English. That is what
the catalog and the deterministic check compare against.

What is specific here: brands and models written in katakana or Chinese
characters (ウィルソン, 威尔胜, クラッシュ100), counters and numerals in words
(三罐, 2足, un par), weekdays (金曜日, 周五, viernes, vendredi), other
currencies (euros, 円, 元), and the local ways to say "it doesn't matter".

Deadlines are counted from Monday, 2 November 2026 (TODAY in run_stress_test.py):
by Friday is 4 days, by Wednesday 2, by next Monday 7.

Amounts in explicit_max_cents are in minor units of the named currency
(150 euros -> 15000, 1万5千円 -> 1500000), as for English and Russian.
"""

from __future__ import annotations

from .stress_phrases import StressCase

CASES_ES: list[StressCase] = [
    StressCase("es-clear-1", "clear",
               "Quiero una raqueta Babolat negra, que no sea muy cara.",
               expect={"brand": "Babolat", "color": "black", "price_preference": "cheap"}),
    StressCase("es-clear-2", "clear",
               "Unas zapatillas Asics talla 42, y que se puedan devolver si no me quedan bien.",
               expect={"brand": "ASICS", "size_label": "42", "needs_refundable": True}),
    StressCase("es-model-1", "model",
               "Una Wilson Clash 100 blanca, empuñadura 4 3/8, tiene que llegar el viernes.",
               expect={"brand": "Wilson", "model": "Clash 100", "color": "white",
                       "size_label": "4 3/8", "deadline_days": 4}),
    StressCase("es-qty-1", "quantity in words",
               "Tres botes de pelotas, las más baratas que tengas.",
               expect={"quantity": 3, "price_preference": "cheap"}),
    StressCase("es-qty-2", "quantity in words",
               "Ponme un par de botes de pelotas Head.",
               expect={"quantity": 2, "brand": "HEAD"}),
    StressCase("es-level-1", "level",
               "Es para mi hija, que acaba de empezar a jugar al tenis.",
               expect={"level": "beginner"}),
    StressCase("es-not-1", "negation",
               "Cualquier raqueta para principiante, menos Babolat, por debajo de 150 euros.",
               expect={"brand": None, "brand_not": ("Babolat",), "level": "beginner",
                       "explicit_max_cents": 15000}),
    StressCase("es-soft-1", "caveat -> soft",
               "Mochila negra de Wilson; si no hay negra, el color me da igual.",
               expect={"brand": "Wilson", "color": "black"}, expect_soft=frozenset({"color"})),
    StressCase("es-money-1", "money",
               "Algo para jugar en el club, como mucho 120 dólares.",
               expect={"explicit_max_cents": 12000, "price_preference": None}),
    StressCase("es-deadline-1", "deadline",
               "Lo necesito para el miércoles sin falta: una raqueta Head azul.",
               expect={"brand": "HEAD", "color": "blue", "deadline_days": 2}),
    StressCase("es-empty-1", "empty",
               "Hola, ¿qué tal?",
               expect={"brand": None, "quantity": None, "level": None}),
    StressCase("es-contra-1", "contradiction",
               "La más barata que tengas, pero que sea de gama alta, de las que usan los profesionales.",
               expect=None, note="contradiction: both signals, the model must not resolve it"),
]

