/** Every pixel of a sprite as [x, y, red]. */
export function pixels(sprite: Sprite): [number, number, boolean][] {
  const out: [number, number, boolean][] = [];
  sprite.rows.forEach((row, y) =>
    [...row].forEach((c, x) => {
      if (c === "#" || c === "r") out.push([x, y, c === "r"]);
    }),
  );
  return out;
}
