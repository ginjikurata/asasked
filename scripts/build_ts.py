"""Write the parts of the TypeScript package that must match Python exactly.

ts/src/prompt.ts: the extraction prompt, response schema and enums, copied
from llm_extract.py so both libraries ask the model the same question.

ts/test/vectors.json (with --vectors): inputs and answers of the Python
checks, recorded while the Python test suite runs. The TypeScript tests feed
the same inputs to the TypeScript checks and expect the same answers.

Run after changing llm_extract.py or the checks:
    python scripts/build_ts.py --vectors
"""

from __future__ import annotations

import dataclasses
import json
import sys
from pathlib import Path

from asasked import llm_extract

ROOT = Path(__file__).resolve().parents[1]


def write_prompt() -> Path:
    out = ROOT / "ts" / "src" / "prompt.ts"
    parts = [
        "// Generated by scripts/build_ts.py from src/asasked/llm_extract.py. Do not edit.\n",
        f"export const COLORS: readonly string[] = {json.dumps(llm_extract.COLORS)};\n",
        f"export const WEEKDAYS: readonly string[] = {json.dumps(llm_extract.WEEKDAYS)};\n",
        f"export const SOFTENABLE_FIELDS: readonly string[] = "
        f"{json.dumps(llm_extract.SOFTENABLE_FIELDS)};\n",
        f"export const SYSTEM_PROMPT: string = {json.dumps(llm_extract.SYSTEM_PROMPT, ensure_ascii=False)};\n",
        f"export const RESPONSE_SCHEMA: Record<string, unknown> = "
        f"{json.dumps(llm_extract.RESPONSE_SCHEMA, indent=2)};\n",
    ]
    out.write_text("".join(parts), encoding="utf-8")
    return out


# --- vectors -----------------------------------------------------------------

LIMIT = 400  # vectors kept per function: enough variety, a small file


def _facts(f) -> dict:
    out = {}
    for fl in dataclasses.fields(f):
        v = getattr(f, fl.name)
        if isinstance(v, frozenset):
            v = sorted(v)
        elif isinstance(v, tuple):
            v = [dict(x) if isinstance(x, dict) else x for x in v]
        out[fl.name] = v
    return out


def _findings(fs) -> list:
    return [dataclasses.asdict(f) for f in fs]


def record_vectors(test_args: list[str]) -> Path:
    import importlib
    import pkgutil

    import pytest

    import asasked
    from asasked import coherence, guard, payment

    for m in pkgutil.iter_modules(asasked.__path__):
        try:
            importlib.import_module(f"asasked.{m.name}")
        except ImportError:
            pass

    vectors: dict[str, dict[str, dict]] = {}

    def keep(kind: str, case: dict) -> None:
        try:
            text = json.dumps(case, sort_keys=True, ensure_ascii=False, allow_nan=False)
        except (TypeError, ValueError):
            return
        bucket = vectors.setdefault(kind, {})
        if text not in bucket and len(bucket) < LIMIT:
            bucket[text] = case

    def products(find, skus) -> dict:
        return {s: dict(find(s)) for s in dict.fromkeys(skus)}

    def check_coherence(facts, purchase, allowed_band, allowlist=(), find=coherence.catalog.find,
                        spent_before_cents=0):
        verdict = original["check_coherence"](facts, purchase, allowed_band, allowlist, find,
                                              spent_before_cents)
        purchase = [list(x) for x in purchase]
        keep("coherence", {
            "facts": _facts(facts), "purchase": purchase, "allowlist": list(allowlist),
            "products": products(find, [s for s, _ in purchase] + list(allowlist)),
            "spent_before_cents": spent_before_cents,
            "coherent": verdict.coherent, "findings": _findings(verdict.findings)})
        return verdict

    def check_payment(facts, payment_, total_cents, over_limit=False, payees=(),
                      spent_before_cents=0):
        out = original["check_payment"](facts, payment_, total_cents, over_limit, payees,
                                        spent_before_cents)
        keep("payment", {
            "facts": _facts(facts), "payment": payment_, "total_cents": total_cents,
            "over_limit": over_limit, "payees": list(payees),
            "spent_before_cents": spent_before_cents, "findings": _findings(out)})
        return out

    def parse_payment(value):
        try:
            out = original["parse_payment"](value)
        except ValueError as e:
            keep("parse_payment", {"input": value, "raises": str(e)})
            raise
        keep("parse_payment", {"input": value, "output": out})
        return out

    def merge_facts(results, strict=False):
        out = original["merge_facts"](results, strict)
        keep("merge", {"results": [_facts(r) for r in results], "strict": strict,
                       "output": _facts(out)})
        return out

    def extract_intent(request, deadline_days=None, provider=None, today=None):
        answers = []
        model = coherence.call_model

        def call(*a, **k):
            answers.append(model(*a, **k))
            return answers[-1]
        coherence.call_model = call
        try:
            out = original["extract_intent"](request, deadline_days, provider, today)
        except coherence.ExtractionError as e:
            if len(answers) == 1:
                keep("extract", {"data": answers[0], "request": request,
                                 "deadline_days": deadline_days, "today": today,
                                 "raises": str(e)})
            raise
        finally:
            coherence.call_model = model
        if len(answers) == 1:
            keep("extract", {"data": answers[0], "request": request,
                             "deadline_days": deadline_days, "today": today,
                             "output": _facts(out)})
        return out

    def interval_name(value):
        out = original["_interval_name"](value)
        keep("interval_name", {"input": value, "output": out})
        return out

    def plain_yes(answer):
        out = original["plain_yes"](answer)
        keep("plain_yes", {"input": answer, "output": out})
        return out

    def guard_check(self, purchase, mandate=None, find=None, payment=None, spent_before=0):
        before = {"agreed": {k: list(v) for k, v in self._agreed.items()},
                  "unchecked_approved": self._unchecked_approved}
        try:
            out = original["check"](self, purchase, mandate=mandate, find=find,
                                    payment=payment, spent_before=spent_before)
        except ValueError as e:
            out = {"raises": str(e)}
        if self.claimed:
            if "raises" in out:
                raise ValueError(out["raises"])
            return out
        case = {**before, "payees": list(self.payees), "payment": payment,
                "spent_before": spent_before,
                "facts": _facts(self._facts) if self._facts is not None else None,
                "error": self._error,
                "allowlist": list(mandate.allowlist) if mandate else []}
        if find is None:
            case["cart"] = purchase
        else:
            case["purchase"] = [list(x) for x in purchase]
            case["products"] = products(find, [s for s, _ in purchase] + case["allowlist"])
        keep("guard", {**case, "result": out})
        if "raises" in out:
            raise ValueError(out["raises"])
        return out

    wrappers = {"check_coherence": check_coherence, "check_payment": check_payment,
                "parse_payment": parse_payment, "merge_facts": merge_facts,
                "extract_intent": extract_intent, "_interval_name": interval_name,
                "plain_yes": plain_yes}
    homes = {"check_coherence": coherence, "check_payment": payment,
             "parse_payment": payment, "merge_facts": coherence,
             "extract_intent": coherence, "_interval_name": coherence, "plain_yes": guard}
    original = {name: getattr(homes[name], name) for name in wrappers}
    original["check"] = guard.Guard.check
    # Replace the function wherever a module imported it by name.
    for mod in [m for n, m in sys.modules.items() if n.startswith("asasked")]:
        for name, fn in wrappers.items():
            if getattr(mod, name, None) is original[name]:
                setattr(mod, name, fn)
    guard.Guard.check = guard_check

    code = pytest.main(["-q", "-p", "no:cacheprovider", *test_args])
    if code != 0:
        raise SystemExit(f"the Python tests failed ({code}): vectors not written")
    out = ROOT / "ts" / "test" / "vectors.json"
    out.parent.mkdir(exist_ok=True)
    data = {k: list(v.values()) for k, v in sorted(vectors.items())}
    out.write_text(json.dumps(data, ensure_ascii=False, indent=1, sort_keys=True) + "\n",
                   encoding="utf-8")
    print({k: len(v) for k, v in data.items()})
    return out


if __name__ == "__main__":
    print(write_prompt())
    if "--vectors" in sys.argv:
        tests = [a for a in sys.argv[1:] if a != "--vectors"] or [
            str(ROOT / "tests"), "--ignore", str(ROOT / "tests" / "test_live.py")]
        print(record_vectors(tests))
